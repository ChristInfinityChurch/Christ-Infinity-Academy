  function make36Weeks(courseTitle, topics) {
    const out = [];
    for (let i = 0; i < 36; i++) {
      const w = i + 1;
      const qtr = Math.ceil(w / 9);
      const t = topics[i] || `${courseTitle} — Unit ${Math.ceil(w / 4)} Lesson ${((w - 1) % 4) + 1}`;
      out.push({
        weekNum: w,
        quarter: qtr,
        title: `Week ${w}: ${t}`,
        daysCompleted: 0,
        masteryScore: null,
        status: w === 1 ? "Current Week" : "5 Days Ready"
      });
    }
    return out;
  }

